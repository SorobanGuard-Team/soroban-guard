use std::path::PathBuf;

use anyhow::Result;
use sorobanguard_core::{check::CheckStatus, pipeline::PipelineReport};

use crate::Reporter;

pub struct MarkdownReporter {
    path: PathBuf,
}

impl MarkdownReporter {
    pub fn new(path: PathBuf) -> Self {
        Self { path }
    }
}

fn status_emoji(status: &CheckStatus) -> &'static str {
    match status {
        CheckStatus::Passed => "✅",
        CheckStatus::Failed => "❌",
        CheckStatus::Skipped => "⏭️",
        CheckStatus::Warning => "⚠️",
    }
}

impl Reporter for MarkdownReporter {
    fn report(&self, report: &PipelineReport) -> Result<()> {
        let mut md = String::new();

        md.push_str("# SorobanGuard Validation Report\n\n");
        md.push_str(&format!("**Project:** `{}`  \n", report.project.name));
        md.push_str(&format!("**Version:** `{}`  \n", report.project.version));
        md.push_str(&format!(
            "**Run at:** {}  \n",
            report.started_at.format("%Y-%m-%d %H:%M:%S UTC")
        ));
        md.push_str(&format!("**Duration:** {:.2}s  \n\n", report.total_duration_secs));

        // Overall badge
        if report.overall_passed() {
            md.push_str("## Result: ✅ All checks passed\n\n");
        } else {
            md.push_str("## Result: ❌ Validation failed\n\n");
        }

        md.push_str(&format!("_{}_\n\n", report.summary_line()));

        // Checks table
        md.push_str("## Check Results\n\n");
        md.push_str("| Check | Status | Duration | Notes |\n");
        md.push_str("|---|---|---|---|\n");

        for result in &report.results {
            let notes = result
                .error
                .as_deref()
                .or(result.output.as_deref())
                .unwrap_or("")
                .lines()
                .next()
                .unwrap_or("")
                .chars()
                .take(100)
                .collect::<String>();

            md.push_str(&format!(
                "| {} | {} {} | {:.2}s | {} |\n",
                result.name,
                status_emoji(&result.status),
                result.status,
                result.duration.as_secs_f64(),
                notes,
            ));
        }

        md.push('\n');

        // Failures detail
        let failures = report.failed();
        if !failures.is_empty() {
            md.push_str("## Failed Checks\n\n");
            for f in &failures {
                md.push_str(&format!("### ❌ {}\n\n", f.name));
                if let Some(err) = &f.error {
                    md.push_str(&format!("**Error:** {err}\n\n"));
                }
                if let Some(hint) = &f.fix_hint {
                    md.push_str(&format!("**Fix:** {hint}\n\n"));
                }
                if let Some(output) = &f.output {
                    md.push_str("<details><summary>Output</summary>\n\n```\n");
                    md.push_str(output);
                    md.push_str("\n```\n\n</details>\n\n");
                }
            }
        }

        // Toolchain info
        md.push_str("## Toolchain\n\n");
        if let Some(rv) = &report.toolchain.rust_version {
            md.push_str(&format!("- **Rust:** `{rv}`\n"));
        }
        if let Some(sv) = &report.toolchain.stellar_cli_version {
            md.push_str(&format!("- **Stellar CLI:** `{sv}`\n"));
        }
        md.push_str(&format!(
            "- **wasm32v1-none target:** {}\n",
            if report.toolchain.wasm_target_installed { "installed" } else { "missing" }
        ));

        // WASM artifact info
        if let Some(wasm) = &report.wasm_artifact {
            md.push_str("\n## WASM Artifact\n\n");
            md.push_str(&format!("- **Path:** `{}`\n", wasm.path.display()));
            md.push_str(&format!("- **Size:** {:.1} KiB\n", wasm.size_kb()));
            md.push_str(&format!("- **Valid WASM:** {}\n", wasm.is_valid_wasm));
            md.push_str(&format!("- **Exports:** {}\n", wasm.exports.join(", ")));
        }

        md.push_str("\n---\n*Generated by [SorobanGuard](https://github.com/your-org/sorobanguard)*\n");

        std::fs::write(&self.path, md)?;
        println!("  Markdown report written to: {}", self.path.display());
        Ok(())
    }
}
